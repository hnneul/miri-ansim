// 문장마다 줄을 나눈다 — 규칙과 이유는 lib/serviceinfo.ts 첫 주석에 있다.
// 한 줄로 흘리면 "…확인하지 / 못했어요. 지도 앱에서…" 처럼 한 덩어리 말이 줄에서 갈리고
// 문장 끝과 다음 문장 시작이 한 줄에 섞인다.
//
// **글자에 \n 을 박지 않고 그리는 자리에서 나눈다.** 화면에 뜨는 안내 중에는 원본에
// 줄바꿈을 넣어둘 수 없는 게 섞여 있다 — 카카오 길찾기가 준 사유(lib/route.ts 사람말),
// 지오코딩 오류(lib/geocode.ts), 코스 생성 오류(app/trip/course/actions.ts) 가 그렇다.
// 한 자리에서 나누면 그 셋도 같이 걸린다.
//
// 쓰는 쪽은 className 에 whitespace-pre-line 을 같이 준다. 이게 빠지면 \n 이 공백으로
// 그려져서 아무 일도 안 일어난다.
//
// 문장 부호 뒤 **공백이 있을 때만** 나눈다. "1.5m"·"(.env.local 확인)" 처럼 점 뒤에
// 글자가 바로 붙는 것은 문장 끝이 아니다. 말줄임(…)도 뺐다 — "찾는 중…" 은 한 문장이다.
export const 문장줄 = (글: string) => 글.replace(/(?<=[.!?])\s+/g, "\n");
