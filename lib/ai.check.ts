// AI 응답 검증기 검증 — node --experimental-strip-types lib/ai.check.ts
//
// 네트워크를 타지 않는다. 여기서 지켜야 할 건 모델이 좋은 문장을 쓰는가가 아니라,
// **나쁜 응답을 확실히 버리는가**다. 검증기가 새면 계획서의 "확인되지 않은 위험요인은
// 생성하지 않는다"가 프롬프트에 적힌 부탁으로만 남는다 — 모델은 언제든 어길 수 있다.
//
// 실제 모델 응답 확인은 lib/ai.smoke.ts 가 한다 (키가 필요해 따로 뒀다).

import assert from "node:assert";
import { verify, promptOf, factsOf, type Facts } from "./ai.ts";
import { scoreRoutes, type DriverProfile, type RiskFactor } from "./score.ts";

const 초보: DriverProfile = {
  experienceYears: 1,
  drivingFrequency: "low",
  jejuExperience: false,
  vehicleSize: "compact",
  timeOfDay: "day",
};

const risk = (type: RiskFactor["type"], label: string, exposure: number): RiskFactor => ({
  type,
  label,
  location: "서귀포시 남원읍 하례리",
  coord: [33.3, 126.6],
  value: "급커브 42곳",
  exposure,
  source: "테스트",
});

// stats 는 근거 화면 비교표와 같은 값이다. 대본 ②(추천 이유)가 여기서 나온다 —
// 좌회전 12번 → 3번이 "굽은 길이 많다"보다 훨씬 구체적인 이유다 (lib/ai.ts RouteFacts.비교).
const 경로 = [
  { name: "5.16도로 경유", badge: "내비 최단거리", durationMin: 63, distanceKm: 43, risks: [risk("sharpCurve", "연속 급커브", 0.29)],
    stats: { turns: 12, roundabouts: 2, sharpCurves: 17, narrow: 0.31, highSpeedKm: 0 } },
  { name: "평화로 경유", badge: "맞춤 저부담", durationMin: 58, distanceKm: 52.8, risks: [risk("highSpeed", "고속주행 구간", 0.48)],
    stats: { turns: 3, roundabouts: 0, sharpCurves: 0, narrow: 0.03, highSpeedKm: 25.4 } },
];
const result = scoreRoutes(초보, 경로[0], 경로[1]);
/**
 * 도착지 주차장 — 대본 ④칸의 재료.
 * **추정 평행**(노상)으로 잡았다. 여기가 대본이 거짓말하기 제일 쉬운 자리라서다 —
 * 확인됨=false 인데 "평행주차입니다"라고 단정하면 초보에게 정반대 방법을 가르치게 된다.
 */
const 도착 = {
  주차장: "매일올레시장 공영주차장",
  요금: "무료",
  주차형태: { 형태: "평행주차" as const, 확인됨: false },
  목적지까지도보분: 4,
};
const facts = factsOf("제주공항 → 서귀포 매일올레시장", 초보, result, 경로, 도착);
const prompt = promptOf(facts);

// --- ① 사실 묶음에 필요한 게 다 담기는가 ---
assert.equal(facts.경로.length, 2);
assert.equal(facts.추천경로, "평화로 경유", "추천은 계산이 정한 값이어야 한다");
assert.ok(facts.운전자조건.includes("운전경력 1년 이하"), "가중치 조건이 빠졌다");
assert.ok(facts.경로[0].요인[0].행동수칙.includes("커브"), "행동수칙을 AI에게 줘야 한다");
// 프롬프트에 사실이 실제로 들어갔는가 — 숫자 검증이 이 문자열을 기준으로 돈다
assert.ok(prompt.includes("63") && prompt.includes("52.8"), "소요시간·거리가 프롬프트에 없다");
// 요인별 점수는 주지 않는다 — 모델이 다른 경로의 점수를 붙이는 걸 막으려고 뺐다
// 여는 따옴표까지 붙여 본다 — 그냥 `점수":` 로 보면 경로 단위 `"부담점수":` 에 걸린다
assert.ok(!prompt.includes('"점수":'), "요인에 점수가 실려 있다");
assert.ok(prompt.includes('"부담점수":'), "경로 단위 부담점수는 있어야 한다");

// 요인은 부담이 큰 순서여야 한다. 두 경로에 같은 이름의 요인이 있을 때가 함정이다 —
// breakdown 을 factor 만으로 찾으면 항상 fast 행이 잡혀 safe 의 정렬이 뒤집힌다.
// 실제로 그렇게 틀렸고, 모델이 "부담이 가장 큰 요인은 (2순위 요인)"이라고 말해서 드러났다.
const 같은이름 = factsOf("정렬", 초보, ...(() => {
  const rs = [
    { ...경로[0], risks: [risk("narrowRoad", "좁은 교행 구간", 0.31), risk("sharpCurve", "연속 급커브", 0.29)] },
    { ...경로[1], risks: [risk("narrowRoad", "좁은 교행 구간", 0.03), risk("highSpeed", "고속주행 구간", 0.48)] },
  ];
  return [scoreRoutes(초보, rs[0], rs[1]), rs] as const;
})());
// safe: 좁은 교행 5.1 < 고속주행 24.4 — 여기가 뒤집혔던 자리다
assert.equal(같은이름.경로[1].요인[0].이름, "고속주행 구간", "safe 요인 정렬이 뒤집혔다");
// fast: 좁은 교행 31.5 < 급커브 35.3 (노출은 좁은 교행이 크지만 기본점수가 급커브가 높다)
assert.equal(같은이름.경로[0].요인[0].이름, "연속 급커브", "fast 요인 정렬이 틀렸다");

// --- ② 정상 응답은 통과한다 ---
// 숫자는 이 픽스처가 실제로 계산한 값이어야 한다 (fast 35.3 / safe 24.4).
// 처음엔 실제 화면에서 본 63.5를 적었다가 ④의 검증에 걸렸다 — 검증기가 의도대로 동작한다는 뜻이다.
const 정상 = {
  summary: "5.16도로 경유는 5분 더 걸리고 부담점수도 35.3점으로 더 높습니다.",
  briefing: [
    "평화로 경유를 추천합니다. 5.16도로 경유는 부담점수 35.3점으로 부담이 더 큽니다.",
    "고속주행 구간이 부담이 큽니다. 주변 차가 빨라도 무리해서 속도를 맞출 필요는 없습니다.",
  ],
  // 경로별 판정. 경로 이름으로 맞춘다 — 순서만 믿으면 뒤집혀도 스키마를 통과한다.
  verdicts: [
    { 경로: "5.16도로 경유", 판정: "굽은 길이 길게 이어집니다. 커브마다 속도를 줄였다 올리기를 반복하게 됩니다." },
    { 경로: "평화로 경유", 판정: "이 길을 추천합니다. 넓은 길이라 차선을 지키기만 하면 됩니다." },
  ],
  // 출발 전 음성 대본. ①성격 ②추천이유 ③각오할것 ④도착 — 칸마다 역할이 다르다.
  // 숫자를 일부러 거의 안 썼다: 귀로 듣는 자리라 "아홉 번"처럼 말로 푸는 쪽이 맞고,
  // 그렇게 쓰면 숫자 검증에도 안 걸린다 (한글 수사는 \d 가 아니다).
  radio: [
    {
      경로: "5.16도로 경유",
      대본: [
        "5.16도로로 넘어가는 길이에요. 산길이라 굽이가 계속 이어지는 편입니다.",
        "이쪽을 고르셨네요. 거리는 짧은 대신 커브를 반복해서 넘는 만큼을 내주게 됩니다.",
        "커브마다 속도를 줄였다 올리기를 반복하게 됩니다. 커브에 들어가기 전에 미리 속도를 줄이세요.",
        "도착지 주차장은 무료예요. 도로변이라 평행주차일 가능성이 높으니 대는 법을 미리 보고 가시면 좋습니다.",
      ],
    },
    {
      경로: "평화로 경유",
      대본: [
        "평화로로 가는 길이에요. 큰길 위주라 차선만 지키면 되는 편한 길입니다.",
        "이 길을 권한 건 좌회전 때문이에요. 맞은편 차 흐름을 끊고 들어가야 하는 순간이 크게 줄어듭니다.",
        "다만 주변 차가 빨라지는 구간이 길게 이어집니다. 무리해서 속도를 맞출 필요는 없습니다.",
        "도착지 주차장은 무료예요. 도로변이라 평행주차일 가능성이 높으니 대는 법을 미리 보고 가시면 좋습니다.",
      ],
    },
  ],
};
/** 판정 하나만 바꿔 끼운다 — 나머지는 정상 응답 그대로 */
const 판정바꿔 = (경로: string, 판정: string) => ({
  ...정상,
  verdicts: 정상.verdicts.map((v) => (v.경로 === 경로 ? { ...v, 판정 } : v)),
});
/** 한 경로의 대본에서 칸 하나만 바꿔 끼운다 (칸: 0=① 1=② 2=③ 3=④) */
const 대본바꿔 = (경로: string, 칸: number, 글: string) => ({
  ...정상,
  radio: 정상.radio.map((r) =>
    r.경로 === 경로 ? { ...r, 대본: r.대본.map((s, i) => (i === 칸 ? 글 : s)) } : r,
  ),
});
/** 대본 배열째로 바꿔 끼운다 — 칸 수·타입이 망가진 응답을 볼 때 쓴다 */
const 대본통째 = (대본: unknown) => ({
  ...정상,
  radio: [{ 경로: "5.16도로 경유", 대본 }, 정상.radio[1]],
});
assert.ok(verify(정상, facts), "정상 응답이 걸러졌다");
assert.equal(verify(정상, facts)!.briefing.length, 2);

// --- ②-2 경로별 판정 (근거 팝업 머리말) ---
// 기호로 받아 **경로 순서**로 펴야 한다. 여기가 어긋나면 평화로 카드에 5.16도로 설명이 붙는다.
assert.deepEqual(
  verify(정상, facts)!.verdicts,
  [정상.verdicts[0].판정, 정상.verdicts[1].판정],
  "판정이 경로 순서로 안 펴졌다",
);
// 모델이 순서를 뒤집어 보내도 이름으로 맞춘다 — 여기가 새면 평화로 카드에 5.16도로 설명이 붙는다
assert.deepEqual(
  verify({ ...정상, verdicts: [...정상.verdicts].reverse() }, facts)!.verdicts,
  [정상.verdicts[0].판정, 정상.verdicts[1].판정],
  "순서가 뒤집힌 응답을 이름으로 되돌리지 못했다",
);
// 있지도 않은 경로 이름으로 오면 버린다
assert.equal(verify({ ...정상, verdicts: [{ 경로: "없는길 경유", 판정: "가" }, 정상.verdicts[1]] }, facts), null);

// 장황한 판정은 버린다. 초보에게 하는 말이 이 길이가 되면 반드시 수치 나열로 흐르고,
// 그건 바로 아래 요인 목록이 이미 하는 일이다. 아래 문장은 실제로 화면에 떴던 100자짜리다.
assert.equal(
  verify(
    판정바꿔(
      "5.16도로 경유",
      "고속주행 구간이 25.4km(제한속도 80km/h)이며 연속 급커브가 17곳(최소 반경 17m)·굽은 구간 2.5km으로, 속도를 무리 맞추지 않고 커브에 진입 전 속도를 줄이면 안전합니다.",
    ),
    facts,
  ),
  null,
  "수치를 나열한 장황한 판정이 통과했다",
);
// 걸러야 하는 건 길이가 아니라 나열이다 — 짧아도 숫자가 셋이면 아래 요인 목록과 같은 말이 된다
assert.equal(
  verify(판정바꿔("5.16도로 경유", "급커브 42곳, 굽은 구간 12.5km, 최소 반경 7m입니다."), facts),
  null,
  "숫자를 나열한 판정이 통과했다",
);
// 두 문장짜리 평문은 통과한다 (프롬프트가 부탁하는 모양). 숫자 하나까지는 괜찮다.
assert.ok(
  verify(판정바꿔("5.16도로 경유", "굽은 길이 경로의 29%나 이어집니다. 커브마다 속도를 줄였다 올리기를 반복하게 됩니다."), facts),
  "두 문장 평문 판정이 걸러졌다",
);

// 한쪽이 없거나 비면 통째로 버린다 — 한 카드만 설명이 없는 화면보다 둘 다 규칙 문장이 낫다
for (const bad of [
  [정상.verdicts[0]],
  [정상.verdicts[0], { 경로: "평화로 경유", 판정: "   " }],
  [정상.verdicts[0], { 경로: "평화로 경유", 판정: 42 }],
  [],
])
  assert.equal(verify({ ...정상, verdicts: bad }, facts), null, `걸러야 한다: ${JSON.stringify(bad)}`);

// 판정에도 금지어·미확인 숫자 검증이 걸린다 (요약·브리핑과 같은 기준)
assert.equal(verify(판정바꿔("5.16도로 경유", "사고다발 지점을 지납니다."), facts), null);
assert.equal(verify(판정바꿔("5.16도로 경유", "급커브가 118곳 있습니다."), facts), null);
assert.ok(verify(판정바꿔("5.16도로 경유", "급커브 42곳을 지납니다."), facts), "사실에 있는 숫자는 통과해야 한다");

// 그 카드에 다른 길의 요인이 붙으면 버린다 — 기호로 순서는 막았지만 내용 뒤바뀜은 여기서만 걸린다.
// 5.16도로(A)에는 고속주행 구간이 없다.
assert.equal(verify(판정바꿔("5.16도로 경유", "고속주행 구간이 이어집니다."), facts), null, "다른 경로의 요인이 판정에 통과했다");
assert.equal(verify(판정바꿔("평화로 경유", "연속 급커브가 이어집니다."), facts), null, "다른 경로의 요인이 판정에 통과했다");

// --- ②-3 출발 전 음성 대본 (radio) ---
// 판정과 같은 함정을 그대로 물려받는다. 다른 점은 **칸마다 기준이 다르다**는 것 하나다.
assert.deepEqual(
  verify(정상, facts)!.radio,
  [정상.radio[0].대본, 정상.radio[1].대본],
  "대본이 경로 순서로 안 펴졌다",
);
// 순서가 뒤집혀 와도 이름으로 맞춘다 — 여기가 새면 평화로를 골랐는데 5.16도로 설명이 재생된다
assert.deepEqual(
  verify({ ...정상, radio: [...정상.radio].reverse() }, facts)!.radio,
  [정상.radio[0].대본, 정상.radio[1].대본],
  "순서가 뒤집힌 대본을 이름으로 되돌리지 못했다",
);
assert.equal(verify({ ...정상, radio: [{ 경로: "없는길 경유", 대본: ["가", "나"] }, 정상.radio[1]] }, facts), null);

// 칸 수·타입이 망가진 대본은 버린다. 한쪽만 재생이 죽은 화면보다 둘 다 규칙 대본이 낫다.
for (const bad of [
  ["한 칸뿐"], // ①만 있으면 안내가 아니다
  ["가", "나", "다", "라", "마"], // 칸이 넷을 넘을 수 없다
  ["가", "   "], // 공백으로 칸 수를 맞추면 안 된다
  ["가", 42],
  "문자열",
  42,
  undefined,
])
  assert.equal(verify(대본통째(bad), facts), null, `걸러야 한다: ${JSON.stringify(bad)}`);

// 한 칸이 길면 버린다 — 귀로는 되감을 수 없어서 긴 문단은 어디를 듣는지 놓친다 (120자 상한)
assert.equal(
  verify(대본바꿔("평화로 경유", 0, "큰길 위주로 이어지는 길이라 차선만 지키면 되는 편한 길인데요, ".repeat(4)), facts),
  null,
  "120자를 넘는 대본 칸이 통과했다",
);

// ★ 여기가 대본에만 있는 규칙이다.
// ②(추천 이유)는 비교가 곧 내용이라 **상대 경로를 언급해야** 한다 — summary 와 같은 취급이다.
assert.ok(
  verify(대본바꿔("평화로 경유", 1, "이 길을 권한 건 연속 급커브를 통째로 피하기 때문이에요."), facts),
  "②에서 상대 경로 요인을 막아버렸다 — 그러면 추천 이유를 말할 수 없다",
);
// 나머지 칸은 그 길 얘기만 해야 한다 — briefing 과 같은 취급이다.
// 평화로에는 연속 급커브가 없다. ①이나 ③에서 그 말이 나오면 듣는 사람은 이 길에 있는 줄 안다.
for (const 칸 of [0, 2, 3])
  assert.equal(
    verify(대본바꿔("평화로 경유", 칸, "연속 급커브가 길게 이어집니다."), facts),
    null,
    `${칸}번 칸에 다른 경로의 요인이 통과했다`,
  );
assert.equal(verify(대본바꿔("5.16도로 경유", 2, "고속주행 구간이 이어집니다."), facts), null);

// 금지어·미확인 숫자는 판정과 같은 기준으로 걸린다
assert.equal(verify(대본바꿔("평화로 경유", 0, "사고다발 지점을 지나는 길이에요."), facts), null);
assert.equal(verify(대본바꿔("평화로 경유", 0, "급커브가 118곳 있는 길이에요."), facts), null);
// 숫자 나열은 막는다 — 귀로 들으면 표보다 더 안 들어온다. 다만 상한이 판정(2)보다 하나 높다:
// 우리가 준 행동수칙이 이미 숫자를 쓴다("1차로보다 2차로가 편합니다") — lib/ai.ts 대본_최대숫자.
assert.ok(
  verify(대본바꿔("평화로 경유", 2, "고속주행이 경로의 48%로 이어져요. 1차로보다 2차로가 편합니다."), facts),
  "행동수칙을 그대로 쓴 대본을 막아버렸다 — 우리 문장을 우리가 거부하는 셈이다",
);
assert.equal(
  verify(대본바꿔("평화로 경유", 0, "좌회전 3번, 회전교차로 2곳, 고속주행 25.4km, 좁은 길 3%인 길이에요."), facts),
  null,
  "숫자를 나열한 대본이 통과했다",
);

// 머리 기호는 떼고 쓴다 — 소리로 나가는 글에서 "①"은 그대로 읽힌다.
// 프롬프트로 말려도 실제로 어겼다("① 이 길은 평화로를 따라…").
assert.equal(
  verify(대본바꿔("평화로 경유", 0, "① 큰길 위주로 가는 길이에요."), facts)!.radio[1][0],
  "큰길 위주로 가는 길이에요.",
  "머리 기호를 안 뗐다",
);
for (const [붙은것, 벗은것] of [
  ["1. 큰길 위주로 가는 길이에요.", "큰길 위주로 가는 길이에요."],
  ["- 큰길 위주로 가는 길이에요.", "큰길 위주로 가는 길이에요."],
])
  assert.equal(verify(대본바꿔("평화로 경유", 0, 붙은것), facts)!.radio[1][0], 벗은것);
// ★ 경로 이름의 소수점을 기호로 오인하면 안 된다 — "5.16도로 경유"가 "16도로 경유"가 된다
assert.equal(
  verify(대본바꿔("5.16도로 경유", 0, "5.16도로 타고 가는 길이에요."), facts)!.radio[0][0],
  "5.16도로 타고 가는 길이에요.",
  "경로 이름의 '5.'을 머리 기호로 잘라먹었다",
);

// --- ②-4 비교표가 실려야 대본 ②가 이유를 말할 수 있다 ---
// 요인만으로는 "굽은 길이 많다"에서 멈춘다. 두 길이 어떻게 다른지는 이 표에서만 나온다.
// 프롬프트 전체가 아니라 **사실 묶음의 직렬화**만 본다 — RULES 본문에도 "비교" 라는 말이
// 들어 있어서 prompt.includes 로는 뭘 넣든 늘 통과한다 (실제로 그렇게 새는 검사를 썼었다).
assert.ok(JSON.stringify(facts).includes('"비교"'), "비교표가 사실 묶음에 안 실렸다");
assert.equal(facts.경로[0].비교?.좌회전유턴, "12번");
assert.equal(facts.경로[1].비교?.좌회전유턴, "3번");
// 요인과 달리 0도 담는다 — 비교에서는 오히려 0 쪽이 요지다 ("급커브 17곳 → 없음")
assert.equal(facts.경로[1].비교?.연속급커브, "없음", "0을 '없음'으로 안 적으면 비교가 안 된다");
assert.equal(facts.경로[0].비교?.고속주행, "없음");
// stats 를 안 주면 프롬프트에서 비교가 통째로 빠진다. 객체가 아니라 **프롬프트**로 확인한다 —
// 값이 undefined 면 키는 남아서 `"비교" in obj` 는 true 지만 JSON.stringify 는 빼기 때문이다.
// 모델이 읽는 건 프롬프트고, 거기 `"비교": null` 이 남으면 그걸 사실로 읽는다.
assert.ok(
  !JSON.stringify(factsOf("무stats", 초보, result, 경로.map(({ stats: _, ...r }) => r))).includes("비교"),
  "stats 없이도 비교 키가 사실 묶음에 남았다",
);

// --- ②-5 도착지 주차장 (대본 ④칸) ---
assert.equal(facts.도착?.주차형태?.확인됨, false, "추정을 확정으로 넘기면 안 된다");
assert.ok(prompt.includes("평행주차") && prompt.includes("매일올레시장"), "도착 사실이 프롬프트에 없다");
// 주차장을 안 거쳐 온 흐름이면 통째로 빠진다 — 그때 대본은 ④칸을 쓰지 않는다
assert.equal(factsOf("무주차장", 초보, result, 경로).도착, undefined);

// --- ③ 확인되지 않은 요인을 말하면 버린다 (계획서 원칙) ---
const 금지문장 = [
  "이 구간은 사고다발 지점을 2곳 지납니다.",
  "급경사 구간이 이어집니다.",
  "안개가 끼면 더 위험합니다.",
  "날씨에 따라 달라질 수 있습니다.",
  "어린이보호구역을 지납니다.",
];
for (const s of 금지문장)
  assert.equal(verify({ ...정상, briefing: [정상.briefing[0], s] }, facts), null, `걸러야 한다: ${s}`);
// summary 쪽도 같은 기준으로 본다 — 근거 카드에 올라가는 문장이다
assert.equal(verify({ ...정상, summary: "사고다발구간이 더 많습니다." }, facts), null);

// --- ④ 주지 않은 숫자를 만들면 버린다 ---
assert.equal(
  verify({ ...정상, briefing: [정상.briefing[0], "급커브가 118곳 있습니다."] }, facts),
  null,
  "사실에 없는 숫자를 통과시켰다",
);
// 사실에 있는 숫자는 통과한다 (43km, 42곳은 프롬프트에 있다)
assert.ok(verify({ ...정상, briefing: [정상.briefing[0], "43km 구간에 급커브 42곳이 있습니다."] }, facts));

// --- ④-2 브리핑은 추천 경로의 요인만 말한다 (Supporting 2 완료 기준) ---
// 추천은 평화로(safe)이므로 5.16도로에만 있는 "연속 급커브"는 브리핑에 못 나온다.
// 실제 모델이 이걸 어기는 걸 봤다 — 프롬프트 지시만으로는 안 막힌다.
assert.equal(facts.추천경로, "평화로 경유");
assert.equal(
  verify({ ...정상, briefing: [정상.briefing[0], "연속 급커브 구간에서는 미리 속도를 줄이세요."] }, facts),
  null,
  "추천하지 않는 경로의 요인이 브리핑에 통과했다",
);
// 같은 이름의 요인이 양쪽에 다 있으면 언급해도 위반이 아니다
const 공통 = factsOf("테스트", 초보, result, [
  { ...경로[0], risks: [risk("narrowRoad", "좁은 교행 구간", 0.29)] },
  { ...경로[1], risks: [risk("narrowRoad", "좁은 교행 구간", 0.48)] },
]);
assert.ok(
  verify(
    {
      summary: "두 경로 모두 좁은 교행 구간이 있습니다.",
      briefing: ["평화로 경유를 추천합니다.", "좁은 교행 구간에서는 넓은 곳에서 기다렸다가 교행하세요."],
      verdicts: [
        { 경로: "5.16도로 경유", 판정: "좁은 교행 구간이 있어 마주 오는 차가 있으면 비켜서야 합니다." },
        { 경로: "평화로 경유", 판정: "이 길을 추천합니다. 좁은 교행 구간이 짧습니다." },
      ],
      // 도착 사실이 없는 facts 다 — ④칸 없이 세 칸으로도 통과해야 한다
      radio: [
        {
          경로: "5.16도로 경유",
          대본: [
            "산길로 넘어가는 길이에요. 폭이 좁아지는 데가 있습니다.",
            "이쪽을 고르셨네요. 거리가 짧은 대신 좁아지는 구간을 더 지나게 됩니다.",
            "마주 오는 차가 오면 넓은 곳에서 미리 기다렸다가 교행하세요.",
          ],
        },
        {
          경로: "평화로 경유",
          대본: [
            "큰길 위주로 가는 길이에요. 좁아지는 데가 짧은 편입니다.",
            "이 길을 권한 건 좁아지는 구간을 덜 지나서예요.",
            "그래도 좁아지면 넓은 곳에서 미리 기다렸다가 교행하세요.",
          ],
        },
      ],
    },
    공통,
  ),
  "양쪽에 공통인 요인은 브리핑에 쓸 수 있어야 한다",
);
// summary 에서 두 경로를 비교하는 건 막지 않는다 (Supporting 1 이 요구하는 일이다)
assert.ok(
  verify({ ...정상, summary: "5.16도로 경유는 연속 급커브가 있어 부담이 더 큽니다." }, facts),
  "summary 의 경로 비교를 막아버렸다",
);

// --- ⑤ 문장 수 제약 (완료 기준 "2~3개의 짧은 문장") ---
assert.equal(verify({ ...정상, briefing: ["한 문장뿐"] }, facts), null, "1문장은 미달이다");
assert.equal(verify({ ...정상, briefing: ["가", "나", "다", "라"] }, facts), null, "4문장은 초과다");
// 빈 문장은 개수에서 빼고 센다 — 공백으로 개수를 맞추면 안 된다
assert.equal(verify({ ...정상, briefing: [정상.briefing[0], "  "] }, facts), null);

// --- ⑥ 망가진 응답 ---
for (const bad of [null, undefined, 42, "문자열", {}, { summary: "요약만" }, { briefing: ["가", "나"] }, { summary: "", briefing: ["가", "나"] },
  // 판정 없이 온 응답 — 필드가 늘었으니 예전 모양은 더 이상 정상이 아니다
  { summary: 정상.summary, briefing: 정상.briefing },
  // 대본 없이 온 응답도 마찬가지다. 재생 버튼이 붙는 화면에서 대본만 비면 앞뒤가 안 맞는다
  { summary: 정상.summary, briefing: 정상.briefing, verdicts: 정상.verdicts }])
  assert.equal(verify(bad, facts), null, `걸러야 한다: ${JSON.stringify(bad)}`);

