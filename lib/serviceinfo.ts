/** 백분율로 적을 때 0.05 → "5%" (0.30000000000000004 같은 꼬리를 안 만든다) */
const pct = (ratio: number) => `${Math.round(ratio * 100)}%`;

/**
 * 글 한 덩이. 세 가지면 네 화면이 다 그려진다 —
 *   h    소제목
 *   p    문단 (회색 박스). label 을 달면 주황 제목이 붙은 강조 박스가 된다
 *   rows 카드 목록. k 제목 · d 설명 · v 오른쪽 값. numbered 면 왼쪽에 01 · 02 뱃지
 *
 * numbered 는 "01, 02, 03 …" 으로 세어 읽는 목록에만 단다 (원본 목록, 저장되는 곳).
 * 조건이나 지침처럼 순서가 뜻이 없는 카드에는 안 단다 — 번호가 있으면 순서를 읽게 된다.
 */
export type Block =
  | { h: string }
  | { p: string; label?: string }
  | { rows: { k: string; d?: string; v?: string }[]; numbered?: true };

