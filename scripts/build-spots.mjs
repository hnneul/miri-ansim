/**
 * 관광공사 TourAPI 에서 **사진만** 가져온다 (KorService2 areaBasedList2).
 *
 * 왜 사진만인가 — TourAPI 는 제주 관광지를 1,200건 가까이 주는데 그중 뭐가 유명한지는
 * 안 알려준다(조회수 같은 인기도 필드가 없다). "가새기오름"이 성산일출봉과 같은 자격으로
 * 섞여 나온다. 그래서 **무엇을 보여줄지는 위 손 목록이 정하고, 사진만 여기서 채운다.**
 * 좌표도 카카오 것을 쓴다 — 경로 계산에 들어가는 값이라 관광지 대표점보다 정확해야 한다.
 */
const TOUR_KEY_RAW = process.env.TOUR_API_KEY ?? readFileSync(".env.local", "utf8").match(/^TOUR_API_KEY=(.+)$/m)?.[1].trim();
// Encoding 키를 그대로 URLSearchParams 에 넣으면 이중 인코딩돼 인증이 깨진다
const TOUR_KEY = TOUR_KEY_RAW?.includes("%") ? decodeURIComponent(TOUR_KEY_RAW) : TOUR_KEY_RAW;

/** 이름 대조용. 공백·괄호·가운뎃점을 지워 "오설록 티뮤지엄" 과 "오설록티뮤지엄" 을 같게 본다. */
const 정규화 = (s) => s.replace(/[\s()·.,'’-]/g, "");

/** 제주 전체 관광 콘텐츠. 관광지·문화시설·레포츠·쇼핑을 받는다 (시장이 쇼핑에 있다). */
async function 관광공사표() {
  if (!TOUR_KEY) {
    console.warn("⚠ TOUR_API_KEY 없음 — 사진 없이 만든다");
    return new Map();
  }
  const 표 = new Map();
  for (const contentTypeId of ["12", "14", "28", "38"]) {
    const q = new URLSearchParams({
      serviceKey: TOUR_KEY, MobileOS: "ETC", MobileApp: "miri-ansim", _type: "json",
      numOfRows: "1000", pageNo: "1", lDongRegnCd: "50", arrange: "C", contentTypeId,
    });
    const res = await fetch(`http://apis.data.go.kr/B551011/KorService2/areaBasedList2?${q}`);
    const j = await res.json();
    for (const it of j.response?.body?.items?.item ?? []) 표.set(정규화(it.title), it);
  }
  return 표;
}

/** 목록에서 못 찾은 곳은 키워드로 한 번 더 묻는다 — 표기가 조금 다른 경우가 많다. */
async function 키워드로(name) {
  if (!TOUR_KEY) return null;
  const q = new URLSearchParams({
    serviceKey: TOUR_KEY, MobileOS: "ETC", MobileApp: "miri-ansim", _type: "json",
    numOfRows: "5", pageNo: "1", arrange: "C", keyword: name, lDongRegnCd: "50",
  });
  try {
    const j = await (await fetch(`http://apis.data.go.kr/B551011/KorService2/searchKeyword2?${q}`)).json();
    return (j.response?.body?.items?.item ?? []).find((x) => x.firstimage) ?? null;
  } catch {
    return null;
  }
}

