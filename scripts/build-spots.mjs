const out = [];
const 실패 = [];
let 사진 = 0;
for (const [name, category] of SPOTS) {
  const g = await geocodePlace(name);
  if ("error" in g || !g?.coord) {
    실패.push(name);
    continue;
  }

  // 사진 붙이기: 목록에서 찾고, 없으면 부분 일치, 그래도 없으면 키워드로 한 번 더
  const k = 정규화(name);
  let t = 관광.get(k);
  if (!t) for (const [키, v] of 관광) if (키.includes(k) || k.includes(키)) { t = v; break; }
  if (!t?.firstimage) t = (await 키워드로(name)) ?? t;
  if (t?.firstimage) 사진++;

  out.push({
    name,
    category,
    at: [+g.coord[0].toFixed(6), +g.coord[1].toFixed(6)],
    // 사람이 눈으로 확인하라고 남긴다 — 엉뚱한 가게가 잡히면 여기서 드러난다
    addr: g.road || g.jibun || null,
    // 카카오가 붙인 분류. "여행 > 관광,명소 > 해수욕장" 의 끝 마디다
    kind: g.type ?? null,
    /**
     * 카드 썸네일 (약 150×100). 없으면 null — 화면이 사진 자리를 비운다.
     *
     * **http 를 https 로 바꿔 둔다.** 관광공사가 절반쯤은 http 로 주는데(실측 105개 중 53개),
     * 배포는 https 라 그대로 두면 브라우저가 mixed content 로 막아 사진이 안 뜬다.
     * 같은 주소가 https 로도 열리는 것은 확인했다.
     */
    thumb: (t?.firstimage2 || t?.firstimage || "").replace(/^http:/, "https:") || null,
    /**
     * 사진 저작권 유형. Type3 은 **변경금지**라 크롭·필터를 걸면 안 된다.
     * 카드에서 object-fit:cover 로 자르므로 화면이 이 값을 보고 처리해야 한다.
     */
    imageRights: t?.cpyrhtDivCd ?? null,
  });
}

